fn name_limit(engine: SchemaEngine) -> usize {
    match engine {
        SchemaEngine::Postgres => 63,
        SchemaEngine::MySql => 64,
        SchemaEngine::Sqlite => MAX_SCHEMA_EDIT_NAME_BYTES,
    }
}

fn name_problem(engine: SchemaEngine, name: &str) -> Option<String> {
    if name.trim().is_empty() {
        return Some("name is empty".into());
    }
    if name.contains('\0') {
        return Some("name contains a NUL character".into());
    }
    let too_long = match engine {
        // MySQL counts characters; PostgreSQL bytes.
        SchemaEngine::MySql => name.chars().count() > 64,
        _ => name.len() > name_limit(engine),
    };
    if too_long || name.len() > MAX_SCHEMA_EDIT_NAME_BYTES {
        return Some(format!(
            "name is longer than {} {}",
            name_limit(engine),
            match engine {
                SchemaEngine::MySql => "characters",
                _ => "bytes",
            }
        ));
    }
    if engine == SchemaEngine::MySql && name.ends_with(' ') {
        return Some("MySQL names cannot end with a space".into());
    }
    None
}

fn fragment_issue(
    issues: &mut Vec<DraftIssue>,
    engine: SchemaEngine,
    object: SchemaObject,
    origin: Origin,
    what: &str,
    text: &str,
) {
    if let Err(error) = check_fragment(text, engine) {
        issues.push(DraftIssue::at(object, origin, format!("{what} {error}")));
    }
}

fn member_issues(
    issues: &mut Vec<DraftIssue>,
    table: &TableModel,
    object: SchemaObject,
    origin: Origin,
    members: &[Origin],
    allow_empty: bool,
) {
    if members.is_empty() && !allow_empty {
        issues.push(DraftIssue::at(object, origin, "has no columns"));
    }
    if members.len() > MAX_SCHEMA_EDIT_MEMBERS {
        issues.push(DraftIssue::at(
            object,
            origin,
            format!("has more than {MAX_SCHEMA_EDIT_MEMBERS} columns"),
        ));
    }
    let mut seen = HashSet::new();
    for member in members {
        if table.column(*member).is_none() {
            issues.push(DraftIssue::at(
                object,
                origin,
                "references a column that is not in the table",
            ));
        } else if !seen.insert(*member) {
            issues.push(DraftIssue::at(object, origin, "lists a column twice"));
        }
    }
}

/// Every problem that keeps the draft from being planned. Engine-specific
/// restrictions (unsupported operations) are the planner's to report; this
/// covers shape, references, names and fragments.
pub fn validate(baseline: &SchemaBaseline, draft: &SchemaDraft) -> Vec<DraftIssue> {
    let engine = baseline.engine;
    let table = &draft.table;
    let mut issues = Vec::new();

    if let Some(problem) = name_problem(engine, &table.name) {
        issues.push(DraftIssue::table(format!("Table {problem}")));
    }
    if table.schema != baseline.table.schema {
        issues.push(DraftIssue::table(
            "Moving a table to another schema is not supported",
        ));
    }
    if table.options != baseline.table.options && engine == SchemaEngine::Postgres {
        issues.push(DraftIssue::table(
            "PostgreSQL has no editable table options",
        ));
    }
    if table
        .comment
        .as_ref()
        .is_some_and(|c| c.len() > MAX_SCHEMA_EDIT_COMMENT_BYTES || c.contains('\0'))
    {
        issues.push(DraftIssue::table(
            "Table comment is too long or contains NUL",
        ));
    }
    if table.columns.is_empty() {
        issues.push(DraftIssue::table("A table needs at least one column"));
    }
    if table.columns.len() > MAX_SCHEMA_EDIT_COLUMNS {
        issues.push(DraftIssue::table(format!(
            "More than {MAX_SCHEMA_EDIT_COLUMNS} columns"
        )));
    }
    for (count, what) in [
        (table.uniques.len(), "unique keys"),
        (table.foreign_keys.len(), "foreign keys"),
        (table.checks.len(), "checks"),
        (table.indexes.len(), "indexes"),
    ] {
        if count > MAX_SCHEMA_EDIT_OBJECTS {
            issues.push(DraftIssue::table(format!(
                "More than {MAX_SCHEMA_EDIT_OBJECTS} {what}"
            )));
        }
    }

    // Origins are unique and existing origins come from the baseline.
    let mut origins = HashSet::new();
    let all_origins = table
        .columns
        .iter()
        .map(|c| (SchemaObject::Column, c.origin))
        .chain(
            table
                .primary_key
                .iter()
                .map(|k| (SchemaObject::PrimaryKey, k.origin)),
        )
        .chain(
            table
                .uniques
                .iter()
                .map(|k| (SchemaObject::Unique, k.origin)),
        )
        .chain(
            table
                .foreign_keys
                .iter()
                .map(|k| (SchemaObject::ForeignKey, k.origin)),
        )
        .chain(table.checks.iter().map(|c| (SchemaObject::Check, c.origin)))
        .chain(
            table
                .indexes
                .iter()
                .map(|i| (SchemaObject::Index, i.origin)),
        );
    let old = &baseline.table;
    for (object, origin) in all_origins {
        if !origins.insert((object, origin)) {
            issues.push(DraftIssue::at(object, origin, "appears twice"));
        }
        if let Origin::New(id) = origin {
            if id.0 >= draft.next_id {
                issues.push(DraftIssue::at(
                    object,
                    origin,
                    "has an identity the draft did not issue",
                ));
            }
        }
        let known = match (object, origin) {
            (_, Origin::New(_)) => true,
            (SchemaObject::Column, o) => old.column(o).is_some(),
            (SchemaObject::PrimaryKey, o) => {
                old.primary_key.as_ref().is_some_and(|k| k.origin == o)
            }
            (SchemaObject::Unique, o) => old.uniques.iter().any(|k| k.origin == o),
            (SchemaObject::ForeignKey, o) => old.foreign_key(o).is_some(),
            (SchemaObject::Check, o) => old.check(o).is_some(),
            (SchemaObject::Index, o) => old.index(o).is_some(),
            (SchemaObject::Table, _) => false,
        };
        if !known {
            issues.push(DraftIssue::at(
                object,
                origin,
                "is not part of the captured table",
            ));
        }
    }

    // Columns.
    let mut names: Vec<&str> = Vec::new();
    for column in &table.columns {
        let origin = column.origin;
        let object = SchemaObject::Column;
        if let Some(problem) = name_problem(engine, &column.name) {
            issues.push(DraftIssue::at(object, origin, format!("Column {problem}")));
        } else if names
            .iter()
            .any(|name| same_name(engine, name, &column.name))
        {
            issues.push(DraftIssue::at(
                object,
                origin,
                format!("Column name {} is used twice", column.name),
            ));
        }
        names.push(&column.name);
        if let Err(error) = check_data_type(&column.data_type, engine) {
            issues.push(DraftIssue::at(object, origin, format!("Type {error}")));
        }
        match &column.default {
            DefaultValue::Expression(sql) => {
                fragment_issue(&mut issues, engine, object, origin, "Default", &sql.0)
            }
            DefaultValue::Literal(text) if text.contains('\0') => issues.push(DraftIssue::at(
                object,
                origin,
                "Default contains a NUL character",
            )),
            _ => {}
        }
        if let Some(generated) = &column.generated {
            fragment_issue(
                &mut issues,
                engine,
                object,
                origin,
                "Generated expression",
                &generated.expression.0,
            );
            if !column.default.is_none() {
                issues.push(DraftIssue::at(
                    object,
                    origin,
                    "A generated column cannot have a default",
                ));
            }
            if column.identity != Identity::None {
                issues.push(DraftIssue::at(
                    object,
                    origin,
                    "A generated column cannot be an identity",
                ));
            }
        }
        match column.identity {
            Identity::Always | Identity::ByDefault => {
                if engine != SchemaEngine::Postgres {
                    issues.push(DraftIssue::at(
                        object,
                        origin,
                        "Identity columns are PostgreSQL only",
                    ));
                }
                if !column.default.is_none() {
                    issues.push(DraftIssue::at(
                        object,
                        origin,
                        "An identity column cannot have a default",
                    ));
                }
                if column.nullable {
                    issues.push(DraftIssue::at(
                        object,
                        origin,
                        "An identity column must be NOT NULL",
                    ));
                }
            }
            Identity::AutoIncrement => {
                if engine == SchemaEngine::Postgres {
                    issues.push(DraftIssue::at(
                        object,
                        origin,
                        "Use an identity column on PostgreSQL",
                    ));
                }
                if !column.default.is_none() {
                    issues.push(DraftIssue::at(
                        object,
                        origin,
                        "An auto-increment column cannot have a default",
                    ));
                }
            }
            Identity::None => {}
        }
        if let Some(on_update) = &column.extra.on_update {
            fragment_issue(
                &mut issues,
                engine,
                object,
                origin,
                "ON UPDATE",
                &on_update.0,
            );
        }
        if column
            .comment
            .as_ref()
            .is_some_and(|c| c.len() > MAX_SCHEMA_EDIT_COMMENT_BYTES || c.contains('\0'))
        {
            issues.push(DraftIssue::at(
                object,
                origin,
                "Comment is too long or contains NUL",
            ));
        }
        for (what, value) in [
            ("Collation", &column.collation),
            ("Character set", &column.extra.charset),
        ] {
            if value
                .as_ref()
                .is_some_and(|v| name_problem(engine, v).is_some())
            {
                issues.push(DraftIssue::at(
                    object,
                    origin,
                    format!("{what} is not a valid name"),
                ));
            }
        }
    }

    // Constraint and index names are unique among themselves.
    let mut constraint_names: Vec<String> = Vec::new();
    let mut named =
        |name: Option<&str>, object: SchemaObject, origin: Origin, issues: &mut Vec<DraftIssue>| {
            let Some(name) = name else { return };
            if let Some(problem) = name_problem(engine, name) {
                issues.push(DraftIssue::at(
                    object,
                    origin,
                    format!("{} {problem}", object.label()),
                ));
            } else if constraint_names
                .iter()
                .any(|other| same_name(engine, other, name))
            {
                issues.push(DraftIssue::at(
                    object,
                    origin,
                    format!("Name {name} is used twice"),
                ));
            }
            constraint_names.push(name.to_owned());
        };

    if let Some(key) = &table.primary_key {
        named(
            key.name.as_deref(),
            SchemaObject::PrimaryKey,
            key.origin,
            &mut issues,
        );
        member_issues(
            &mut issues,
            table,
            SchemaObject::PrimaryKey,
            key.origin,
            &key.columns,
            false,
        );
        for member in &key.columns {
            if table
                .column(*member)
                .is_some_and(|c| c.generated.as_ref().is_some_and(|g| !g.stored))
            {
                issues.push(DraftIssue::at(
                    SchemaObject::PrimaryKey,
                    key.origin,
                    "A virtual generated column cannot be in the primary key",
                ));
            }
        }
    }
    for key in &table.uniques {
        named(
            key.name.as_deref(),
            SchemaObject::Unique,
            key.origin,
            &mut issues,
        );
        member_issues(
            &mut issues,
            table,
            SchemaObject::Unique,
            key.origin,
            &key.columns,
            false,
        );
    }
    for key in &table.foreign_keys {
        let object = SchemaObject::ForeignKey;
        named(key.name.as_deref(), object, key.origin, &mut issues);
        member_issues(&mut issues, table, object, key.origin, &key.columns, false);
        if let Some(problem) = name_problem(engine, &key.referenced_table) {
            issues.push(DraftIssue::at(
                object,
                key.origin,
                format!("Referenced table {problem}"),
            ));
        }
        if let Some(problem) = key
            .referenced_schema
            .as_deref()
            .and_then(|s| name_problem(engine, s))
        {
            issues.push(DraftIssue::at(
                object,
                key.origin,
                format!("Referenced schema {problem}"),
            ));
        }
        let implicit = key.referenced_columns.is_empty() && engine == SchemaEngine::Sqlite;
        if !implicit && key.referenced_columns.len() != key.columns.len() {
            issues.push(DraftIssue::at(
                object,
                key.origin,
                "Column and referenced column counts differ",
            ));
        }
        if key
            .referenced_columns
            .iter()
            .any(|c| name_problem(engine, c).is_some())
        {
            issues.push(DraftIssue::at(
                object,
                key.origin,
                "A referenced column name is invalid",
            ));
        }
    }
    for check in &table.checks {
        named(
            check.name.as_deref(),
            SchemaObject::Check,
            check.origin,
            &mut issues,
        );
        fragment_issue(
            &mut issues,
            engine,
            SchemaObject::Check,
            check.origin,
            "Check",
            &check.expression.0,
        );
    }
    let mut index_names: Vec<&str> = Vec::new();
    for index in &table.indexes {
        let object = SchemaObject::Index;
        if let Some(problem) = name_problem(engine, &index.name) {
            issues.push(DraftIssue::at(
                object,
                index.origin,
                format!("Index {problem}"),
            ));
        } else if index_names
            .iter()
            .any(|other| same_name(engine, other, &index.name))
        {
            issues.push(DraftIssue::at(
                object,
                index.origin,
                format!("Index name {} is used twice", index.name),
            ));
        }
        index_names.push(&index.name);
        if index.members.is_empty() {
            issues.push(DraftIssue::at(object, index.origin, "has no members"));
        }
        if index.members.len() > MAX_SCHEMA_EDIT_MEMBERS {
            issues.push(DraftIssue::at(
                object,
                index.origin,
                format!("has more than {MAX_SCHEMA_EDIT_MEMBERS} members"),
            ));
        }
        let columns: Vec<Origin> = index
            .members
            .iter()
            .filter_map(|member| match &member.target {
                IndexTarget::Column(origin) => Some(*origin),
                IndexTarget::Expression(_) => None,
            })
            .collect();
        member_issues(&mut issues, table, object, index.origin, &columns, true);
        member_issues(
            &mut issues,
            table,
            object,
            index.origin,
            &index.include,
            true,
        );
        for member in &index.members {
            if let IndexTarget::Expression(sql) = &member.target {
                fragment_issue(
                    &mut issues,
                    engine,
                    object,
                    index.origin,
                    "Index expression",
                    &sql.0,
                );
            }
            if member
                .collation
                .as_ref()
                .is_some_and(|v| name_problem(engine, v).is_some())
            {
                issues.push(DraftIssue::at(
                    object,
                    index.origin,
                    "Collation is not a valid name",
                ));
            }
        }
        if let Some(predicate) = &index.predicate {
            fragment_issue(
                &mut issues,
                engine,
                object,
                index.origin,
                "Predicate",
                &predicate.0,
            );
        }
        if let Some(method) = &index.method {
            if method.is_empty()
                || !method
                    .chars()
                    .all(|c| c.is_ascii_alphanumeric() || c == '_')
            {
                issues.push(DraftIssue::at(
                    object,
                    index.origin,
                    "Index method is not a plain name",
                ));
            }
        }
    }
    issues
}

