fn split_type(text: &str) -> (String, Vec<u64>, String) {
    // `base(args) suffix`, all normalized. Args that are not integers make
    // the type opaque (returned with no parsed args and the raw text).
    let normalized = normalize_type(text);
    let Some(open) = normalized.find('(') else {
        // Multi-word bases (`double precision`, `character varying`) stay
        // whole; only trailing integer attributes are a suffix.
        for attribute in [" unsigned zerofill", " unsigned", " signed", " zerofill"] {
            if let Some(base) = normalized.strip_suffix(attribute) {
                return (base.to_owned(), Vec::new(), attribute.trim().to_owned());
            }
        }
        return (normalized, Vec::new(), String::new());
    };
    let Some(close) = normalized[open..].find(')').map(|offset| open + offset) else {
        return (normalized, Vec::new(), String::new());
    };
    let base = normalized[..open].trim().to_owned();
    let args: Option<Vec<u64>> = normalized[open + 1..close]
        .split(',')
        .map(|arg| arg.trim().parse().ok())
        .collect();
    let suffix = normalized[close + 1..].trim().to_owned();
    match args {
        Some(args) => (base, args, suffix),
        None => (normalized, Vec::new(), String::new()),
    }
}

fn canonical_base(engine: SchemaEngine, base: &str) -> String {
    let base = match base {
        "character varying" | "varchar2" | "nvarchar" => "varchar",
        "character" | "nchar" | "bpchar" => "char",
        "int2" => "smallint",
        "int" | "int4" | "integer" if engine == SchemaEngine::Postgres => "integer",
        "int" | "integer" => "int",
        "int8" => "bigint",
        "decimal" => "numeric",
        "float4" => "real",
        "float8" | "double precision" | "double" => "double",
        other => other,
    };
    base.to_owned()
}

fn rank(ladder: &[&str], base: &str) -> Option<usize> {
    ladder.iter().position(|step| *step == base)
}

/// True when every value of `before` is representable in `after` without
/// loss: `varchar(n)` to a larger or unbounded `varchar`, `varchar` to
/// `text`, a wider integer of the same signedness, a wider `numeric` with the
/// same scale, `real` to `double`. Anything not provably widening is not.
pub fn is_widening(engine: SchemaEngine, before: &str, after: &str) -> bool {
    if types_equal(before, after) {
        return true;
    }
    let (b_base, b_args, b_suffix) = split_type(before);
    let (a_base, a_args, a_suffix) = split_type(after);
    let b_base = canonical_base(engine, &b_base);
    let a_base = canonical_base(engine, &a_base);
    // Signedness and other trailing attributes must match exactly.
    if b_suffix != a_suffix {
        return false;
    }
    match (b_base.as_str(), a_base.as_str()) {
        ("varchar", "varchar") | ("varbinary", "varbinary") => {
            match (b_args.as_slice(), a_args.as_slice()) {
                ([n], [m]) => m >= n,
                (_, []) => engine == SchemaEngine::Postgres,
                _ => false,
            }
        }
        ("varchar" | "char", "text") if engine != SchemaEngine::MySql => true,
        ("varchar" | "char" | "tinytext" | "text", "mediumtext" | "longtext")
        | ("tinytext" | "mediumtext", "longtext")
        | ("tinytext", "text" | "mediumtext")
        | ("tinyblob", "blob" | "mediumblob" | "longblob")
        | ("blob", "mediumblob" | "longblob")
        | ("mediumblob", "longblob")
            if engine == SchemaEngine::MySql =>
        {
            true
        }
        ("char", "varchar") if engine != SchemaEngine::MySql => {
            // Padding semantics differ, but no value is lost.
            match (b_args.as_slice(), a_args.as_slice()) {
                ([n], [m]) => m >= n,
                (_, []) => true,
                _ => false,
            }
        }
        ("numeric", "numeric") => match (b_args.as_slice(), a_args.as_slice()) {
            ([p, s], [q, t]) => s == t && q >= p,
            ([p], [q]) => q >= p,
            (_, []) => engine == SchemaEngine::Postgres,
            _ => false,
        },
        ("real", "double") => true,
        (b, a) => {
            let ladder: &[&str] = match engine {
                SchemaEngine::Postgres => &["smallint", "integer", "bigint"],
                SchemaEngine::MySql => &["tinyint", "smallint", "mediumint", "int", "bigint"],
                SchemaEngine::Sqlite => &["smallint", "int", "bigint"],
            };
            if let (Some(from), Some(to)) = (rank(ladder, b), rank(ladder, a)) {
                return to >= from;
            }
            if engine == SchemaEngine::Postgres
                && rank(ladder, b).is_some()
                && a == "numeric"
                && a_args.is_empty()
            {
                return true;
            }
            false
        }
    }
}

