#[derive(Debug, Serialize, Deserialize, Clone, PartialEq, Eq)]
#[serde(rename_all = "camelCase")]
pub(crate) struct AlterColumnTypeOp {
    pub schema: String,
    pub table: String,
    pub name: String,
    pub new_type: String,
    pub using: Option<String>,
}

impl ObjectOperation for AlterColumnTypeOp {
    fn validate(&self, op_index: usize) -> Result<(), PgObjectError> {
        let Self {
            schema,
            table,
            name,
            new_type,
            using,
        } = self;
        {
            require_table(op_index, schema, table)?;
            require_name(op_index, "column", name)?;
            validate_data_type(op_index, "new type", new_type)?;
            if let Some(using) = using {
                validate_fragment(
                    op_index,
                    "USING expression",
                    using,
                    FragmentContext::Embedded,
                )?;
            }
            Ok(())
        }
    }

    fn fragments(&self) -> Vec<&str> {
        std::iter::once(self.new_type.as_str())
            .chain(self.using.iter().map(String::as_str))
            .collect()
    }

    fn render(&self, _op_index: usize) -> Result<RenderedOp, PgObjectError> {
        let Self {
            schema,
            table,
            name,
            new_type,
            using,
        } = self;
        let rendered = RenderedOp {
            sql: format!(
                "ALTER TABLE {} ALTER COLUMN {} TYPE {}{};",
                qualified(schema, table),
                quote_double(name),
                new_type,
                using
                    .as_ref()
                    .map(|expression| format!(" USING {expression}"))
                    .unwrap_or_default()
            ),
            summary: format!("Change type of {schema}.{table}.{name} to {new_type}"),
            destructive: true,
            transactional: true,
        };
        Ok(rendered)
    }
}

