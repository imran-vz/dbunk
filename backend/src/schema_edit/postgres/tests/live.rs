//! Live round trips against the fixture server: capture, plan, apply,
//! capture again.
use super::super::{catalog, executor};
use crate::backend::table_ddl::WritePermit;
use crate::postgres::connect_spec::ResolvedPostgresConnectSpec;
use crate::postgres::dedicated::{self, DriverJoins, NoticeSink};
use crate::schema_edit::*;
use crate::PgDriverOptions;
use std::time::Duration;
use tokio::sync::watch;

const SCHEMA: &str = "schema_edit_live";

fn live_spec() -> ResolvedPostgresConnectSpec {
    ResolvedPostgresConnectSpec {
        connection_id: "schema-edit-live".into(),
        host: "127.0.0.1".into(),
        port: 15432,
        database: "dbunk_demo".into(),
        user: "dbunk".into(),
        password: "dbunk".into(),
        tls: crate::postgres::tls::ResolvedTls::prefer("127.0.0.1"),
        connect_timeout: Some(Duration::from_secs(5)),
        keepalive: None,
        driver_options: PgDriverOptions::default(),
        safety_policy: Default::default(),
    }
}

async fn run_sql(spec: &ResolvedPostgresConnectSpec, sql: &str) {
    let connection = dedicated::connect(spec, NoticeSink::Ignore)
        .await
        .expect("connect");
    connection.client.batch_execute(sql).await.expect("setup SQL");
    connection.close().await;
}

async fn fresh(spec: &ResolvedPostgresConnectSpec, table: &str) {
    run_sql(
        spec,
        &format!(
            "CREATE SCHEMA IF NOT EXISTS {SCHEMA};
DROP TABLE IF EXISTS {SCHEMA}.{table} CASCADE;
CREATE TABLE {SCHEMA}.{table} (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email varchar(100) NOT NULL CONSTRAINT {table}_email_key UNIQUE,
  name text DEFAULT 'anon',
  score int,
  CONSTRAINT {table}_email_check CHECK (length(email) > 3)
);
CREATE INDEX {table}_name_idx ON {SCHEMA}.{table} (name);"
        ),
    )
    .await;
}

async fn capture(spec: &ResolvedPostgresConnectSpec, table: &str) -> SchemaBaseline {
    let (_sender, cancellation) = watch::channel(0u64);
    catalog::capture(
        spec,
        &DriverJoins::default(),
        cancellation,
        SchemaEditRequest::new(SCHEMA, table),
    )
    .await
    .expect("capture")
}

async fn apply(
    spec: &ResolvedPostgresConnectSpec,
    baseline: &SchemaBaseline,
    draft: &SchemaDraft,
    options: &PlanOptions,
) -> SchemaEditOutcome {
    let preview = plan_review(baseline, draft, options).expect("plans");
    let permit = WritePermit::test_permit();
    let cancellation = permit.test_cancellation();
    executor::execute(
        spec.clone(),
        DriverJoins::default(),
        permit,
        cancellation,
        baseline.clone(),
        draft.clone(),
        preview,
    )
    .await
}

fn column<'a>(table: &'a TableModel, name: &str) -> &'a ColumnModel {
    table
        .columns
        .iter()
        .find(|column| column.name == name)
        .unwrap_or_else(|| panic!("column {name}"))
}

#[tokio::test]
#[ignore = "requires make -C infrastructure/test-db postgres"]
async fn round_trip_applies_and_recaptures_the_draft() {
    let spec = live_spec();
    let table = "round_trip";
    fresh(&spec, table).await;
    let baseline = capture(&spec, table).await;
    assert_eq!(baseline.editable, Editability::Editable);
    let mut draft = SchemaDraft::from_baseline(&baseline);
    let by_name = |draft: &SchemaDraft, name: &str| {
        draft
            .table
            .columns
            .iter()
            .find(|c| c.name == name)
            .unwrap()
            .origin
    };
    let id = by_name(&draft, "id");
    let name = by_name(&draft, "name");
    let score = by_name(&draft, "score");

    draft.table.comment = Some("Round trip".into());
    draft.table.column_mut(id).unwrap().identity = Identity::Always;
    let renamed = draft.table.column_mut(name).unwrap();
    renamed.name = "full_name".into();
    renamed.comment = Some("Display name".into());
    let retyped = draft.table.column_mut(score).unwrap();
    retyped.data_type = "bigint".into();
    retyped.nullable = false;
    retyped.default = DefaultValue::Expression(SqlFragment::new("0"));
    let nick = draft.add_column("nick", "varchar(20)");
    draft.table.column_mut(nick).unwrap().default = DefaultValue::Literal("x".into());
    let total = draft.add_column("total", "bigint");
    draft.table.column_mut(total).unwrap().generated = Some(Generated {
        expression: SqlFragment::new("id * 2"),
        stored: true,
    });
    draft.table.checks.clear();
    let check = draft.new_origin();
    draft.table.checks.push(CheckModel {
        origin: check,
        name: None,
        expression: SqlFragment::new("score >= 0"),
        enforced: true,
    });
    draft.table.uniques[0].name = Some(format!("{table}_email_uq"));
    draft.table.indexes[0].name = format!("{table}_full_name_idx");
    let index = draft.new_origin();
    draft.table.indexes.push(IndexModel {
        origin: index,
        name: format!("{table}_lower_email_idx"),
        unique: false,
        method: None,
        members: vec![IndexMember {
            target: IndexTarget::Expression(SqlFragment::new("lower(email)")),
            descending: true,
            prefix_length: None,
            collation: None,
        }],
        include: vec![id],
        predicate: Some(SqlFragment::new("email IS NOT NULL")),
    });
    let options = PlanOptions {
        concurrent_indexes: vec![index],
        validate_separately: true,
        ..PlanOptions::default()
    };

    let outcome = apply(&spec, &baseline, &draft, &options).await;
    assert!(outcome.applied(), "{outcome:?}");

    let after = capture(&spec, table).await;
    assert_eq!(after.editable, Editability::Editable, "{:?}", after.editable);
    let t = &after.table;
    assert_eq!(t.comment.as_deref(), Some("Round trip"));
    let names: Vec<&str> = t.columns.iter().map(|c| c.name.as_str()).collect();
    assert_eq!(names, ["id", "email", "full_name", "score", "nick", "total"]);
    assert_eq!(column(t, "id").identity, Identity::Always);
    assert_eq!(column(t, "full_name").comment.as_deref(), Some("Display name"));
    assert_eq!(column(t, "score").data_type, "bigint");
    assert!(!column(t, "score").nullable);
    assert_eq!(column(t, "nick").data_type, "character varying(20)");
    assert!(column(t, "total").generated.as_ref().is_some_and(|g| g.stored));
    assert_eq!(t.uniques[0].name.as_deref(), Some("round_trip_email_uq"));
    assert_eq!(t.checks.len(), 1);
    assert_eq!(t.checks[0].name.as_deref(), Some("round_trip_check"));
    let indexes: Vec<&str> = t.indexes.iter().map(|i| i.name.as_str()).collect();
    assert!(indexes.contains(&"round_trip_full_name_idx"), "{indexes:?}");
    assert!(indexes.contains(&"round_trip_lower_email_idx"), "{indexes:?}");

    // The fresh capture is its own fixed point.
    let untouched = SchemaDraft::from_baseline(&after);
    assert_eq!(
        plan_review(&after, &untouched, &PlanOptions::default()),
        Err(PlanError::NoChanges)
    );
}

#[tokio::test]
#[ignore = "requires make -C infrastructure/test-db postgres"]
async fn a_table_changed_after_capture_is_refused_unchanged() {
    let spec = live_spec();
    let table = "drifted";
    fresh(&spec, table).await;
    let baseline = capture(&spec, table).await;
    run_sql(&spec, &format!("ALTER TABLE {SCHEMA}.{table} ADD COLUMN sneaky int")).await;
    let mut draft = SchemaDraft::from_baseline(&baseline);
    draft.add_column("nick", "text");
    assert_eq!(
        apply(&spec, &baseline, &draft, &PlanOptions::default()).await,
        SchemaEditOutcome::NotDispatched {
            reason: SchemaEditFailure::BaselineChanged
        }
    );
    let after = capture(&spec, table).await;
    assert!(after.table.columns.iter().all(|c| c.name != "nick"));
}

#[tokio::test]
#[ignore = "requires make -C infrastructure/test-db postgres"]
async fn a_failing_statement_rolls_back_the_whole_group() {
    let spec = live_spec();
    let table = "rolled_back";
    fresh(&spec, table).await;
    run_sql(
        &spec,
        &format!("INSERT INTO {SCHEMA}.{table}(email, score) VALUES ('someone@example.com', NULL)"),
    )
    .await;
    let baseline = capture(&spec, table).await;
    let mut draft = SchemaDraft::from_baseline(&baseline);
    draft.add_column("nick", "text");
    let score = draft
        .table
        .columns
        .iter()
        .find(|c| c.name == "score")
        .unwrap()
        .origin;
    // Existing NULLs make SET NOT NULL fail after the ADD COLUMN ran.
    draft.table.column_mut(score).unwrap().nullable = false;
    let outcome = apply(&spec, &baseline, &draft, &PlanOptions::default()).await;
    assert!(
        matches!(
            outcome,
            SchemaEditOutcome::RolledBack {
                reason: SchemaEditFailure::Database { .. }
            }
        ),
        "{outcome:?}"
    );
    let after = capture(&spec, table).await;
    assert_eq!(after.table, baseline.table);
}

#[tokio::test]
#[ignore = "requires make -C infrastructure/test-db postgres"]
async fn a_held_lock_times_out_without_dispatch() {
    let spec = live_spec();
    let table = "locked";
    fresh(&spec, table).await;
    let baseline = capture(&spec, table).await;
    let holder = dedicated::connect(&spec, NoticeSink::Ignore)
        .await
        .expect("connect");
    holder
        .client
        .batch_execute(&format!(
            "BEGIN; LOCK TABLE {SCHEMA}.{table} IN ACCESS SHARE MODE"
        ))
        .await
        .expect("hold lock");
    let mut draft = SchemaDraft::from_baseline(&baseline);
    draft.add_column("nick", "text");
    assert_eq!(
        apply(&spec, &baseline, &draft, &PlanOptions::default()).await,
        SchemaEditOutcome::NotDispatched {
            reason: SchemaEditFailure::LockTimeout
        }
    );
    holder.client.batch_execute("ROLLBACK").await.expect("release");
    holder.close().await;
}
