#[allow(clippy::too_many_arguments)]
fn changed(
    out: &mut Vec<SchemaChange>,
    object: SchemaObject,
    origin: Option<Origin>,
    name: &str,
    field: Field,
    before: impl Into<String>,
    after: impl Into<String>,
    destructive: Option<Destructive>,
) {
    out.push(SchemaChange {
        object,
        origin,
        name: name.to_owned(),
        kind: ChangeKind::Changed {
            field,
            before: before.into(),
            after: after.into(),
        },
        destructive,
    });
}

fn simple(
    out: &mut Vec<SchemaChange>,
    object: SchemaObject,
    origin: Option<Origin>,
    name: &str,
    kind: ChangeKind,
    destructive: Option<Destructive>,
) {
    out.push(SchemaChange {
        object,
        origin,
        name: name.to_owned(),
        kind,
        destructive,
    });
}

/// Object-level and field-level changes from `baseline` to `draft`, in
/// review order: table, columns (draft order, then removed), keys, foreign
/// keys, checks, indexes.
pub fn diff(baseline: &SchemaBaseline, draft: &SchemaDraft) -> SchemaChangeSet {
    let engine = baseline.engine;
    let old = &baseline.table;
    let new = &draft.table;
    let mut out = Vec::new();
    table_changes(&mut out, old, new);
    column_changes(&mut out, engine, old, new);
    key_changes(
        &mut out,
        SchemaObject::PrimaryKey,
        old,
        new,
        old.primary_key.iter(),
        new.primary_key.iter(),
    );
    key_changes(
        &mut out,
        SchemaObject::Unique,
        old,
        new,
        old.uniques.iter(),
        new.uniques.iter(),
    );
    foreign_key_changes(&mut out, old, new);
    check_changes(&mut out, old, new);
    index_changes(&mut out, old, new);
    SchemaChangeSet { changes: out }
}

fn table_changes(out: &mut Vec<SchemaChange>, old: &TableModel, new: &TableModel) {
    let name = new.name.as_str();
    if old.name != new.name {
        simple(
            out,
            SchemaObject::Table,
            None,
            name,
            ChangeKind::Renamed {
                from: old.name.clone(),
                to: new.name.clone(),
            },
            None,
        );
    }
    if old.comment != new.comment {
        changed(
            out,
            SchemaObject::Table,
            None,
            name,
            Field::Comment,
            describe_optional(&old.comment),
            describe_optional(&new.comment),
            None,
        );
    }
    for (field, before, after) in option_changes(&old.options, &new.options) {
        changed(
            out,
            SchemaObject::Table,
            None,
            name,
            field,
            before,
            after,
            None,
        );
    }
}

pub(crate) fn option_changes(
    old: &TableOptions,
    new: &TableOptions,
) -> Vec<(Field, String, String)> {
    let mut fields = Vec::new();
    if old.strict != new.strict {
        fields.push((
            Field::Strict,
            describe_flag(old.strict).into(),
            describe_flag(new.strict).into(),
        ));
    }
    if old.without_rowid != new.without_rowid {
        fields.push((
            Field::WithoutRowid,
            describe_flag(old.without_rowid).into(),
            describe_flag(new.without_rowid).into(),
        ));
    }
    for (field, before, after) in [
        (Field::Engine, &old.engine, &new.engine),
        (Field::Charset, &old.charset, &new.charset),
        (Field::Collation, &old.collation, &new.collation),
        (Field::RowFormat, &old.row_format, &new.row_format),
    ] {
        if before != after {
            fields.push((field, describe_optional(before), describe_optional(after)));
        }
    }
    fields
}

/// Field changes of one existing column, as `ALTER COLUMN` fields.
pub fn column_field_changes(old: &ColumnModel, new: &ColumnModel) -> Vec<ColumnField> {
    let mut fields = Vec::new();
    if !types_equal(&old.data_type, &new.data_type) {
        fields.push(ColumnField::DataType);
    }
    if old.collation != new.collation {
        fields.push(ColumnField::Collation);
    }
    if old.nullable != new.nullable {
        fields.push(ColumnField::Nullable);
    }
    if old.default != new.default {
        fields.push(ColumnField::Default);
    }
    if old.generated != new.generated {
        fields.push(ColumnField::Generated);
    }
    if old.identity != new.identity {
        fields.push(ColumnField::Identity);
    }
    if old.extra.charset != new.extra.charset {
        fields.push(ColumnField::Charset);
    }
    if old.extra.on_update != new.extra.on_update {
        fields.push(ColumnField::OnUpdate);
    }
    if old.extra.invisible != new.extra.invisible {
        fields.push(ColumnField::Invisible);
    }
    fields
}

/// Existing columns whose relative order differs from the baseline, by
/// origin. New columns never count; whether they may be placed mid-table is
/// a planner question.
fn moved_columns(old: &TableModel, new: &TableModel) -> HashSet<Origin> {
    let surviving: HashSet<Origin> = new.columns.iter().map(|c| c.origin).collect();
    let before: Vec<Origin> = old
        .columns
        .iter()
        .map(|c| c.origin)
        .filter(|origin| surviving.contains(origin))
        .collect();
    let after: Vec<Origin> = new
        .columns
        .iter()
        .map(|c| c.origin)
        .filter(|origin| !origin.is_new())
        .collect();
    if before == after {
        return HashSet::new();
    }
    // The fewest columns that moved: those outside a longest common
    // subsequence of the two orders.
    let position: HashMap<Origin, usize> =
        before.iter().enumerate().map(|(i, o)| (*o, i)).collect();
    let sequence: Vec<usize> = after
        .iter()
        .filter_map(|o| position.get(o).copied())
        .collect();
    let kept = longest_increasing(&sequence);
    after
        .iter()
        .enumerate()
        .filter(|(i, _)| !kept.contains(i))
        .map(|(_, origin)| *origin)
        .collect()
}

/// Indexes (into `values`) of one longest strictly increasing subsequence.
fn longest_increasing(values: &[usize]) -> HashSet<usize> {
    let n = values.len();
    let mut length = vec![1usize; n];
    let mut previous = vec![usize::MAX; n];
    for i in 0..n {
        for j in 0..i {
            if values[j] < values[i] && length[j] + 1 > length[i] {
                length[i] = length[j] + 1;
                previous[i] = j;
            }
        }
    }
    let mut kept = HashSet::new();
    let Some(mut at) = (0..n).max_by_key(|i| (length[*i], usize::MAX - *i)) else {
        return kept;
    };
    loop {
        kept.insert(at);
        if previous[at] == usize::MAX {
            break;
        }
        at = previous[at];
    }
    kept
}

fn column_changes(
    out: &mut Vec<SchemaChange>,
    engine: SchemaEngine,
    old: &TableModel,
    new: &TableModel,
) {
    let moved = moved_columns(old, new);
    for column in &new.columns {
        let origin = Some(column.origin);
        let name = column.name.as_str();
        let Some(previous) = old
            .column(column.origin)
            .filter(|_| !column.origin.is_new())
        else {
            let destructive = (!column.nullable
                && column.default.is_none()
                && column.generated.is_none()
                && column.identity == Identity::None)
                .then_some(Destructive::AddNotNullWithoutDefault);
            simple(
                out,
                SchemaObject::Column,
                origin,
                name,
                ChangeKind::Added,
                destructive,
            );
            continue;
        };
        if previous.name != column.name {
            simple(
                out,
                SchemaObject::Column,
                origin,
                name,
                ChangeKind::Renamed {
                    from: previous.name.clone(),
                    to: column.name.clone(),
                },
                None,
            );
        }
        if !types_equal(&previous.data_type, &column.data_type) {
            let destructive = (!is_widening(engine, &previous.data_type, &column.data_type))
                .then_some(Destructive::NarrowingType);
            changed(
                out,
                SchemaObject::Column,
                origin,
                name,
                Field::DataType,
                &previous.data_type,
                &column.data_type,
                destructive,
            );
        }
        if previous.nullable != column.nullable {
            let destructive = (!column.nullable).then_some(Destructive::SetNotNull);
            changed(
                out,
                SchemaObject::Column,
                origin,
                name,
                Field::Nullable,
                describe_nullable(previous.nullable),
                describe_nullable(column.nullable),
                destructive,
            );
        }
        if previous.default != column.default {
            changed(
                out,
                SchemaObject::Column,
                origin,
                name,
                Field::Default,
                describe_default(&previous.default),
                describe_default(&column.default),
                None,
            );
        }
        if previous.generated != column.generated {
            let destructive = column
                .generated
                .is_some()
                .then_some(Destructive::Regenerate);
            changed(
                out,
                SchemaObject::Column,
                origin,
                name,
                Field::Generated,
                describe_generated(&previous.generated),
                describe_generated(&column.generated),
                destructive,
            );
        }
        if previous.identity != column.identity {
            changed(
                out,
                SchemaObject::Column,
                origin,
                name,
                Field::Identity,
                describe_identity(previous.identity),
                describe_identity(column.identity),
                None,
            );
        }
        if previous.collation != column.collation {
            changed(
                out,
                SchemaObject::Column,
                origin,
                name,
                Field::Collation,
                describe_optional(&previous.collation),
                describe_optional(&column.collation),
                None,
            );
        }
        if previous.extra.charset != column.extra.charset {
            changed(
                out,
                SchemaObject::Column,
                origin,
                name,
                Field::Charset,
                describe_optional(&previous.extra.charset),
                describe_optional(&column.extra.charset),
                None,
            );
        }
        if previous.extra.on_update != column.extra.on_update {
            let text = |value: &Option<super::model::SqlFragment>| {
                value
                    .as_ref()
                    .map_or_else(|| "none".to_owned(), |sql| sql.0.clone())
            };
            changed(
                out,
                SchemaObject::Column,
                origin,
                name,
                Field::OnUpdate,
                text(&previous.extra.on_update),
                text(&column.extra.on_update),
                None,
            );
        }
        if previous.extra.invisible != column.extra.invisible {
            changed(
                out,
                SchemaObject::Column,
                origin,
                name,
                Field::Invisible,
                describe_flag(previous.extra.invisible),
                describe_flag(column.extra.invisible),
                None,
            );
        }
        if previous.comment != column.comment {
            changed(
                out,
                SchemaObject::Column,
                origin,
                name,
                Field::Comment,
                describe_optional(&previous.comment),
                describe_optional(&column.comment),
                None,
            );
        }
        if moved.contains(&column.origin) {
            let before = old
                .columns
                .iter()
                .position(|c| c.origin == column.origin)
                .unwrap_or(0)
                + 1;
            let after = new
                .columns
                .iter()
                .position(|c| c.origin == column.origin)
                .unwrap_or(0)
                + 1;
            changed(
                out,
                SchemaObject::Column,
                origin,
                name,
                Field::Position,
                before.to_string(),
                after.to_string(),
                None,
            );
        }
    }
    for column in &old.columns {
        if new.column(column.origin).is_none() {
            simple(
                out,
                SchemaObject::Column,
                Some(column.origin),
                &column.name,
                ChangeKind::Removed,
                Some(Destructive::DropColumn),
            );
        }
    }
}

fn key_label(key: &KeyModel, table: &TableModel) -> String {
    key.name
        .clone()
        .unwrap_or_else(|| format!("({})", table.column_names(&key.columns).join(", ")))
}

type KeyMatch<'a> = (
    Vec<(&'a KeyModel, &'a KeyModel)>,
    Vec<&'a KeyModel>,
    Vec<&'a KeyModel>,
);

/// Generic origin matching for keys, foreign keys, checks and indexes.
fn match_objects<'a, T: 'a>(
    old: impl Iterator<Item = &'a T>,
    new: impl Iterator<Item = &'a T>,
    origin: impl Fn(&T) -> Origin,
) -> (Vec<(&'a T, &'a T)>, Vec<&'a T>, Vec<&'a T>) {
    let old: Vec<&T> = old.collect();
    let new: Vec<&T> = new.collect();
    let mut pairs = Vec::new();
    let mut added = Vec::new();
    for item in &new {
        match old
            .iter()
            .find(|previous| origin(previous) == origin(item) && !origin(item).is_new())
        {
            Some(previous) => pairs.push((*previous, *item)),
            None => added.push(*item),
        }
    }
    let removed = old
        .into_iter()
        .filter(|previous| !new.iter().any(|item| origin(item) == origin(previous)))
        .collect();
    (pairs, added, removed)
}

fn renamed(old: &Option<String>, new: &Option<String>) -> Option<ChangeKind> {
    match (old, new) {
        (Some(from), Some(to)) if from != to => Some(ChangeKind::Renamed {
            from: from.clone(),
            to: to.clone(),
        }),
        _ => None,
    }
}

fn key_changes<'a>(
    out: &mut Vec<SchemaChange>,
    object: SchemaObject,
    old_table: &TableModel,
    new_table: &TableModel,
    old: impl Iterator<Item = &'a KeyModel>,
    new: impl Iterator<Item = &'a KeyModel>,
) {
    let (pairs, added, removed) = match_objects(old, new, |key| key.origin);
    for (previous, key) in pairs {
        let name = key_label(key, new_table);
        if let Some(kind) = renamed(&previous.name, &key.name) {
            simple(out, object, Some(key.origin), &name, kind, None);
        }
        if previous.columns != key.columns {
            changed(
                out,
                object,
                Some(key.origin),
                &name,
                Field::Columns,
                old_table.column_names(&previous.columns).join(", "),
                new_table.column_names(&key.columns).join(", "),
                Some(Destructive::Recreate),
            );
        }
    }
    for key in added {
        simple(
            out,
            object,
            Some(key.origin),
            &key_label(key, new_table),
            ChangeKind::Added,
            None,
        );
    }
    for key in removed {
        simple(
            out,
            object,
            Some(key.origin),
            &key_label(key, old_table),
            ChangeKind::Removed,
            Some(Destructive::DropConstraint),
        );
    }
}

fn foreign_key_label(key: &ForeignKeyModel, table: &TableModel) -> String {
    key.name.clone().unwrap_or_else(|| {
        format!(
            "({}) → {}",
            table.column_names(&key.columns).join(", "),
            describe_reference(key)
        )
    })
}

fn action(value: ReferentialAction) -> String {
    value.sql().to_owned()
}

fn foreign_key_changes(out: &mut Vec<SchemaChange>, old: &TableModel, new: &TableModel) {
    let (pairs, added, removed) =
        match_objects(old.foreign_keys.iter(), new.foreign_keys.iter(), |key| {
            key.origin
        });
    let object = SchemaObject::ForeignKey;
    for (previous, key) in pairs {
        let name = foreign_key_label(key, new);
        let origin = Some(key.origin);
        let recreate = Some(Destructive::Recreate);
        if let Some(kind) = renamed(&previous.name, &key.name) {
            simple(out, object, origin, &name, kind, None);
        }
        if previous.columns != key.columns {
            changed(
                out,
                object,
                origin,
                &name,
                Field::Columns,
                old.column_names(&previous.columns).join(", "),
                new.column_names(&key.columns).join(", "),
                recreate,
            );
        }
        if previous.referenced_schema != key.referenced_schema
            || previous.referenced_table != key.referenced_table
            || previous.referenced_columns != key.referenced_columns
        {
            changed(
                out,
                object,
                origin,
                &name,
                Field::Reference,
                describe_reference(previous),
                describe_reference(key),
                recreate,
            );
        }
        if previous.on_update != key.on_update {
            changed(
                out,
                object,
                origin,
                &name,
                Field::OnUpdateAction,
                action(previous.on_update),
                action(key.on_update),
                recreate,
            );
        }
        if previous.on_delete != key.on_delete {
            changed(
                out,
                object,
                origin,
                &name,
                Field::OnDeleteAction,
                action(previous.on_delete),
                action(key.on_delete),
                recreate,
            );
        }
        if previous.deferrable != key.deferrable {
            changed(
                out,
                object,
                origin,
                &name,
                Field::Deferrable,
                describe_deferrable(previous.deferrable),
                describe_deferrable(key.deferrable),
                recreate,
            );
        }
    }
    for key in added {
        simple(
            out,
            object,
            Some(key.origin),
            &foreign_key_label(key, new),
            ChangeKind::Added,
            None,
        );
    }
    for key in removed {
        simple(
            out,
            object,
            Some(key.origin),
            &foreign_key_label(key, old),
            ChangeKind::Removed,
            Some(Destructive::DropConstraint),
        );
    }
}

fn check_label(check: &CheckModel) -> String {
    check
        .name
        .clone()
        .unwrap_or_else(|| format!("CHECK ({})", check.expression))
}

fn check_changes(out: &mut Vec<SchemaChange>, old: &TableModel, new: &TableModel) {
    let (pairs, added, removed) =
        match_objects(old.checks.iter(), new.checks.iter(), |check| check.origin);
    let object = SchemaObject::Check;
    for (previous, check) in pairs {
        let name = check_label(check);
        let origin = Some(check.origin);
        if let Some(kind) = renamed(&previous.name, &check.name) {
            simple(out, object, origin, &name, kind, None);
        }
        if previous.expression != check.expression {
            changed(
                out,
                object,
                origin,
                &name,
                Field::Expression,
                previous.expression.0.clone(),
                check.expression.0.clone(),
                Some(Destructive::Recreate),
            );
        }
        if previous.enforced != check.enforced {
            changed(
                out,
                object,
                origin,
                &name,
                Field::Enforced,
                describe_flag(previous.enforced),
                describe_flag(check.enforced),
                None,
            );
        }
    }
    for check in added {
        simple(
            out,
            object,
            Some(check.origin),
            &check_label(check),
            ChangeKind::Added,
            None,
        );
    }
    for check in removed {
        simple(
            out,
            object,
            Some(check.origin),
            &check_label(check),
            ChangeKind::Removed,
            Some(Destructive::DropConstraint),
        );
    }
}

fn index_changes(out: &mut Vec<SchemaChange>, old: &TableModel, new: &TableModel) {
    let (pairs, added, removed) =
        match_objects(old.indexes.iter(), new.indexes.iter(), |index| index.origin);
    let object = SchemaObject::Index;
    for (previous, index) in pairs {
        let name = index.name.as_str();
        let origin = Some(index.origin);
        let recreate = Some(Destructive::Recreate);
        if previous.name != index.name {
            simple(
                out,
                object,
                origin,
                name,
                ChangeKind::Renamed {
                    from: previous.name.clone(),
                    to: index.name.clone(),
                },
                None,
            );
        }
        if previous.unique != index.unique {
            changed(
                out,
                object,
                origin,
                name,
                Field::Unique,
                describe_flag(previous.unique),
                describe_flag(index.unique),
                recreate,
            );
        }
        if previous.method != index.method {
            changed(
                out,
                object,
                origin,
                name,
                Field::Method,
                describe_optional(&previous.method),
                describe_optional(&index.method),
                recreate,
            );
        }
        if previous.members != index.members {
            changed(
                out,
                object,
                origin,
                name,
                Field::Members,
                describe_members(previous, old),
                describe_members(index, new),
                recreate,
            );
        }
        if previous.include != index.include {
            changed(
                out,
                object,
                origin,
                name,
                Field::Include,
                old.column_names(&previous.include).join(", "),
                new.column_names(&index.include).join(", "),
                recreate,
            );
        }
        if previous.predicate != index.predicate {
            let text = |value: &Option<super::model::SqlFragment>| {
                value
                    .as_ref()
                    .map_or_else(|| "none".to_owned(), |sql| sql.0.clone())
            };
            changed(
                out,
                object,
                origin,
                name,
                Field::Predicate,
                text(&previous.predicate),
                text(&index.predicate),
                recreate,
            );
        }
    }
    for index in added {
        simple(
            out,
            object,
            Some(index.origin),
            &index.name,
            ChangeKind::Added,
            None,
        );
    }
    for index in removed {
        simple(
            out,
            object,
            Some(index.origin),
            &index.name,
            ChangeKind::Removed,
            Some(Destructive::DropIndex),
        );
    }
}

