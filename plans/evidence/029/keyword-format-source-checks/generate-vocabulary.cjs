const fs = require('node:fs');
const path = require('node:path');
const root = process.cwd();
const base = path.join(root,'node_modules/sql-formatter/dist/cjs');
const {postgresql} = require(path.join(base,'languages/postgresql/postgresql.formatter.js'));
const o = postgresql.tokenizerOptions;
const keywordWords = new Set([o.reservedKeywordPhrases,o.reservedClauses,o.reservedSelect,o.reservedSetOperations,o.reservedJoins,o.reservedKeywords].flat().flatMap(p => p.split(' ')));
const groups = [
  ['KEYWORD_PHRASES',true,o.reservedKeywordPhrases],
  ['TYPE_PHRASES',false,o.reservedDataTypePhrases],
  ['EARLY_KEYWORDS',true,['CASE','END','BETWEEN','LIMIT']],
  ['CLAUSES',true,o.reservedClauses],
  ['SELECT',true,o.reservedSelect],
  ['SET_OPERATIONS',true,o.reservedSetOperations],
  ['CASE_BRANCHES',true,['WHEN','ELSE','THEN']],
  ['JOINS',true,o.reservedJoins],
  ['BOOLEANS',true,['AND','OR']],
  ['FUNCTIONS',false,o.reservedFunctionNames.filter(p=>p.split(' ').some(w=>keywordWords.has(w)))],
  ['TYPES',false,o.reservedDataTypes.filter(p=>p.split(' ').some(w=>keywordWords.has(w)))],
  ['KEYWORDS',true,o.reservedKeywords],
];
const license=fs.readFileSync(path.join(root,'node_modules/sql-formatter/LICENSE'),'utf8');
let out='// PostgreSQL keyword vocabulary from sql-formatter 15.7.4, pinned at Tauri\n// baseline 102568b. Generated by the evidence generator; no runtime dependency.\n// Groups retain tokenizer precedence, with longest phrases first. Only function\n// and type names overlapping keyword vocabulary need explicit preservation.\n/*\n'+license+'*/\n';
out+='pub(super) const GROUPS: &[(&[&str], bool)] = &[\n'+groups.map(([name,upper])=>`    (${name}, ${upper}),`).join('\n')+'\n];\n';
for(const [name,,phrases] of groups){const values=[...new Set(phrases)].sort((a,b)=>b.length-a.length||a.localeCompare(b));out+=`const ${name}: &[&str] = &[\n`+values.map(p=>'    '+JSON.stringify(p)+',').join('\n')+'\n];\n';}
fs.writeFileSync('apps/native/src/sql_format/keyword_vocabulary.rs',out);
fs.writeFileSync('plans/evidence/029/keyword-format-source-checks/vocabulary.json',JSON.stringify({baseline:'102568b',version:'15.7.4',groups:groups.map(([name,uppercase,phrases])=>({name,uppercase,phrases:[...new Set(phrases)]}))},null,2)+'\n');
console.log(groups.map(([name,,p])=>`${name}: ${new Set(p).size}`).join('\n'));
