#[test]
fn endpoints_are_bounded_and_must_share_a_resolved_connection() {
    let e = Endpoint {
        connection_id: "one".into(),
        schema: "a".into(),
    };
    assert!(validate_endpoints("one", &[(Side::Source, &e), (Side::Target, &e)]).is_ok());
    assert_eq!(
        validate_endpoints("other", &[(Side::Source, &e)]),
        Err(CompareError::InvalidRequest)
    );
    assert_eq!(
        validate_endpoints("one", &[]),
        Err(CompareError::InvalidRequest)
    );
}

#[tokio::test]
async fn cancellation_and_deadline_wrap_pending_work() {
    let (tx, rx) = watch::channel(false);
    let control = CaptureControl::new(Instant::now() + Duration::from_secs(60), rx);
    tx.send(true).unwrap();
    assert_eq!(
        control.wait(std::future::pending::<()>()).await,
        Err(CompareError::Cancelled)
    );
    let (_tx, rx) = watch::channel(false);
    let control = CaptureControl::new(Instant::now(), rx);
    assert_eq!(
        control.wait(std::future::pending::<()>()).await,
        Err(CompareError::DeadlineExceeded)
    );
}

