fn field<'a>(capture: &'a CapturedEndpoint, table: &str, path: FieldPath) -> &'a CapturedValue {
    &capture
        .fields()
        .iter()
        .find(|f| capture.table(f.table_oid).unwrap().identity.name == table && f.path == path)
        .unwrap_or_else(|| panic!("missing {table} {path:?}"))
        .value
}

