#[test]
fn new_columns_render_collation_and_generation() {
    let mut spec = column("total", "numeric");
    spec.generated = Some(PgGeneratedColumn {
        expression: "price * qty".into(),
        stored: true,
    });
    let generated = statement(PgObjectOp::AddColumn(AddColumnOp {
        schema: "s".into(),
        table: "t".into(),
        column: spec.clone(),
    }));
    assert_eq!(
        generated.sql,
        r#"ALTER TABLE "s"."t" ADD COLUMN "total" numeric GENERATED ALWAYS AS (price * qty) STORED;"#
    );
    spec.generated.as_mut().unwrap().stored = false;
    assert!(statement(PgObjectOp::AddColumn(AddColumnOp {
        schema: "s".into(),
        table: "t".into(),
        column: spec.clone(),
    }))
    .sql
    .ends_with("GENERATED ALWAYS AS (price * qty) VIRTUAL;"));

    let mut collated = column("name", "text");
    collated.collation = Some("C".into());
    collated.nullable = false;
    assert_eq!(
        statement(PgObjectOp::AddColumn(AddColumnOp {
            schema: "s".into(),
            table: "t".into(),
            column: collated,
        }))
        .sql,
        r#"ALTER TABLE "s"."t" ADD COLUMN "name" text COLLATE "C" NOT NULL;"#
    );

    spec.default = Some(PgDefaultValue::Literal { value: "0".into() });
    assert!(matches!(
        generate_object_ddl(&[PgObjectOp::AddColumn(AddColumnOp {
            schema: "s".into(),
            table: "t".into(),
            column: spec,
        })]),
        Err(PgObjectError::InvalidOp { .. })
    ));
}

#[test]
fn older_column_payloads_still_decode_and_new_fields_are_omitted() {
    let spec: NewColumnSpec = serde_json::from_value(serde_json::json!({
        "name": "c",
        "dataType": "text",
        "nullable": true,
        "default": null
    }))
    .expect("older payload");
    assert_eq!(spec.generated, None);
    assert_eq!(spec.collation, None);
    let value = serde_json::to_value(&spec).expect("serialize");
    assert!(value.get("generated").is_none());
    assert!(value.get("collation").is_none());
}
