//! Generator unit tests: schema-editor alterations.

use super::*;

fn identity(change: PgIdentityChange) -> PlannedStatement {
    statement(PgObjectOp::SetColumnIdentity(SetColumnIdentityOp {
        schema: "s".into(),
        table: "t".into(),
        name: "id".into(),
        change,
    }))
}

#[test]
fn renders_identity_changes() {
    let add = identity(PgIdentityChange::Add {
        identity: PgIdentity::Always,
    });
    assert_eq!(
        add.sql,
        r#"ALTER TABLE "s"."t" ALTER COLUMN "id" ADD GENERATED ALWAYS AS IDENTITY;"#
    );
    assert!(!add.destructive && add.transactional);
    assert_eq!(
        identity(PgIdentityChange::Set {
            identity: PgIdentity::ByDefault
        })
        .sql,
        r#"ALTER TABLE "s"."t" ALTER COLUMN "id" SET GENERATED BY DEFAULT;"#
    );
    assert_eq!(
        identity(PgIdentityChange::Drop).sql,
        r#"ALTER TABLE "s"."t" ALTER COLUMN "id" DROP IDENTITY;"#
    );
}

#[test]
fn renders_generated_expression_changes() {
    let set = statement(PgObjectOp::SetColumnExpression(SetColumnExpressionOp {
        schema: "s".into(),
        table: "t".into(),
        name: "total".into(),
        expression: Some("price * qty".into()),
    }));
    assert_eq!(
        set.sql,
        r#"ALTER TABLE "s"."t" ALTER COLUMN "total" SET EXPRESSION AS (price * qty);"#
    );
    assert!(set.destructive, "recomputes every row");
    let drop = statement(PgObjectOp::SetColumnExpression(SetColumnExpressionOp {
        schema: "s".into(),
        table: "t".into(),
        name: "total".into(),
        expression: None,
    }));
    assert_eq!(
        drop.sql,
        r#"ALTER TABLE "s"."t" ALTER COLUMN "total" DROP EXPRESSION;"#
    );
    assert!(!drop.destructive);
}

#[test]
fn generated_expression_cannot_escape_its_parentheses() {
    assert!(matches!(
        generate_object_ddl(&[PgObjectOp::SetColumnExpression(SetColumnExpressionOp {
            schema: "s".into(),
            table: "t".into(),
            name: "total".into(),
            expression: Some("1), DROP COLUMN x, ALTER COLUMN y SET EXPRESSION AS (1".into()),
        })]),
        Err(PgObjectError::InvalidOp { .. })
    ));
}

#[test]
fn renders_type_change_with_collation() {
    let op = |data_type: &str, collation: &str, using: Option<&str>| {
        PgObjectOp::AlterColumnCollation(AlterColumnCollationOp {
            schema: "s".into(),
            table: "t".into(),
            name: "name".into(),
            data_type: data_type.into(),
            collation: collation.into(),
            using: using.map(Into::into),
        })
    };
    assert_eq!(
        statement(op("text", "C", None)).sql,
        r#"ALTER TABLE "s"."t" ALTER COLUMN "name" TYPE text COLLATE "C";"#
    );
    assert_eq!(
        statement(op("varchar(20)", "en-x-icu", Some("name::varchar(20)"))).sql,
        r#"ALTER TABLE "s"."t" ALTER COLUMN "name" TYPE varchar(20) COLLATE "en-x-icu" USING name::varchar(20);"#
    );
    assert!(generate_object_ddl(&[op("text", " ", None)]).is_err());
    assert!(generate_object_ddl(&[op("text COLLATE \"C\"", "C", None)]).is_err());
}

#[test]
fn renders_constraint_and_index_renames() {
    assert_eq!(
        statement(PgObjectOp::RenameConstraint(RenameConstraintOp {
            schema: "s".into(),
            table: "t".into(),
            name: "t_pkey".into(),
            new_name: "t_pk".into(),
        }))
        .sql,
        r#"ALTER TABLE "s"."t" RENAME CONSTRAINT "t_pkey" TO "t_pk";"#
    );
    let index = statement(PgObjectOp::RenameIndex(RenameIndexOp {
        schema: "s".into(),
        name: "t_name_idx".into(),
        new_name: "t_full_name_idx".into(),
    }));
    assert_eq!(
        index.sql,
        r#"ALTER INDEX "s"."t_name_idx" RENAME TO "t_full_name_idx";"#
    );
    assert!(!index.destructive && index.transactional);
    assert!(
        generate_object_ddl(&[PgObjectOp::RenameIndex(RenameIndexOp {
            schema: "s".into(),
            name: "t_name_idx".into(),
            new_name: "x".repeat(64),
        })])
        .is_err()
    );
    assert!(
        generate_object_ddl(&[PgObjectOp::RenameConstraint(RenameConstraintOp {
            schema: "s".into(),
            table: "t".into(),
            name: "t_pkey".into(),
            new_name: "x".repeat(64),
        })])
        .is_err()
    );
}

