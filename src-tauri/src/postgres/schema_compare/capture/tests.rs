    assert_eq!(orders["changedFields"], 2);
    assert!(orders["incomparableFields"].as_u64().unwrap() > 0);
    drop(page);
    drop(result);
    assert_eq!(budget.used(), 0);
    let missing = Endpoint {
        schema: "missing".into(),
        ..source.clone()
    };
    assert!(matches!(
        capture_resolved(&spec, &[(Side::Source, &missing)], &control, &budget).await,
        Err(CompareError::Unavailable)
    ));
    // Exact UTF-8 field cap, including worst-case sixfold JSON escaping.
    admin
        .client
        .batch_execute("CREATE SCHEMA limits; CREATE TABLE limits.t(id integer)")
        .await
        .unwrap();
    let limits = Endpoint {
        schema: "limits".into(),
        ..source.clone()
    };
    for (bytes, ok) in [(FIELD_BYTES, true), (FIELD_BYTES + 1, false)] {
        admin
            .client
            .batch_execute(&format!(
                "COMMENT ON TABLE limits.t IS {}",
                crate::quote_literal(&"\u{1}".repeat(bytes))
            ))
            .await
            .unwrap();
        let result = capture_resolved(&spec, &[(Side::Source, &limits)], &control, &budget).await;
        if ok {
            assert!(result.is_ok(), "{:?}", result.err());
        } else {
            assert!(matches!(
                result,
                Err(CompareError::LimitExceeded {
                    limit: Limit::FieldBytes
                })
            ));
        }
    }
    assert_eq!(budget.used(), 0);
    // A role can read a schema only when it can lock/read the complete table.
    admin
        .client
        .batch_execute(
            "CREATE ROLE capture_reader LOGIN; GRANT USAGE ON SCHEMA limits TO capture_reader",
        )
        .await
        .unwrap();
