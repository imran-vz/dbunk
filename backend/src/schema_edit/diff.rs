pub fn describe_default(value: &DefaultValue) -> String {
    match value {
        DefaultValue::None => "none".into(),
        DefaultValue::Literal(text) => format!("'{text}'"),
        DefaultValue::Expression(sql) => sql.0.clone(),
    }
}

pub fn describe_generated(value: &Option<Generated>) -> String {
    match value {
        None => "none".into(),
        Some(generated) => format!(
            "AS ({}) {}",
            generated.expression,
            if generated.stored {
                "STORED"
            } else {
                "VIRTUAL"
            }
        ),
    }
}

pub fn describe_identity(value: Identity) -> &'static str {
    match value {
        Identity::None => "none",
        Identity::Always => "GENERATED ALWAYS",
        Identity::ByDefault => "GENERATED BY DEFAULT",
        Identity::AutoIncrement => "AUTO_INCREMENT",
    }
}

fn describe_nullable(nullable: bool) -> &'static str {
    if nullable {
        "NULL"
    } else {
        "NOT NULL"
    }
}

fn describe_optional(value: &Option<String>) -> String {
    value.clone().unwrap_or_else(|| "none".into())
}

fn describe_flag(value: bool) -> &'static str {
    if value {
        "yes"
    } else {
        "no"
    }
}

fn describe_deferrable(value: Deferrable) -> &'static str {
    match value {
        Deferrable::Never => "NOT DEFERRABLE",
        Deferrable::InitiallyImmediate => "DEFERRABLE INITIALLY IMMEDIATE",
        Deferrable::InitiallyDeferred => "DEFERRABLE INITIALLY DEFERRED",
    }
}

fn describe_reference(key: &ForeignKeyModel) -> String {
    let table = match &key.referenced_schema {
        Some(schema) => format!("{schema}.{}", key.referenced_table),
        None => key.referenced_table.clone(),
    };
    if key.referenced_columns.is_empty() {
        table
    } else {
        format!("{table}({})", key.referenced_columns.join(", "))
    }
}

/// Index members as display text, column names resolved in `table`.
pub fn describe_members(index: &IndexModel, table: &TableModel) -> String {
    index
        .members
        .iter()
        .map(|member| {
            let mut text = match &member.target {
                IndexTarget::Column(origin) => table.column_name(*origin).unwrap_or("?").to_owned(),
                IndexTarget::Expression(sql) => format!("({sql})"),
            };
            if let Some(length) = member.prefix_length {
                text.push_str(&format!("({length})"));
            }
            if let Some(collation) = &member.collation {
                text.push_str(&format!(" COLLATE {collation}"));
            }
            if member.descending {
                text.push_str(" DESC");
            }
            text
        })
        .collect::<Vec<_>>()
        .join(", ")
}

/// Engine-aware identifier equality: PostgreSQL identifiers are always quoted
/// by the planners, so case matters; MySQL column names and SQLite names are
/// case-insensitive.
pub fn same_name(engine: SchemaEngine, a: &str, b: &str) -> bool {
    match engine {
        SchemaEngine::Postgres => a == b,
        SchemaEngine::MySql | SchemaEngine::Sqlite => a.eq_ignore_ascii_case(b),
    }
}

pub fn types_equal(a: &str, b: &str) -> bool {
    normalize_type(a) == normalize_type(b)
}

