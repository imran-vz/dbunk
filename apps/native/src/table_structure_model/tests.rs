#[test]
fn primary_and_foreign_key_order_and_navigation_are_not_name_sorted() {
    let mut data = snapshot();
    data.columns[0].primary_key_position = Some(2);
    data.columns[1].primary_key_position = Some(1);
    data.primary_key = Some(StructurePrimaryKey {
        oid: 33,
        name: "pk".into(),
        columns: vec![
            StructureKeyColumn {
                number: 3,
                name: "b".into(),
            },
            StructureKeyColumn {
                number: 1,
                name: "a".into(),
            },
        ],
        deferrable: true,
        initially_deferred: false,
    });
    data.outbound.push(foreign_key());
    let mut inbound = foreign_key();
    inbound.oid = 45;
    inbound.source_oid = 66;
    inbound.source_schema = "incoming".into();
    inbound.source_table = "child".into();
    inbound.target_oid = 22;
    inbound.target_schema = data.schema.clone();
    inbound.target_table = data.table.clone();
    inbound.columns = vec![StructureKeyPair {
        source_number: 8,
        source: "source".into(),
        target_number: 3,
        target: "b".into(),
    }];
    data.inbound.push(inbound);
    let c = capture(data);
    let pk = detail(&c, Section::PrimaryKey, 0);
    assert!(
        pk.find("1. \"b\" (attribute 3)").unwrap() < pk.find("2. \"a\" (attribute 1)").unwrap()
    );
    let fk = detail(&c, Section::ForeignKeys, 0);
    assert!(fk.contains("1. \"b\" (attribute 3) → \"x\" (attribute 8)"));
    assert!(fk.contains("2. \"a\" (attribute 1) → \"y\" (attribute 2)"));
    for text in [
        "ON UPDATE: CASCADE",
        "ON DELETE: SET NULL",
        "MATCH: FULL",
        "Initially deferred: true",
        "Validated: false",
    ] {
        assert!(fk.contains(text));
    }
    assert_eq!(
        c.navigation(Section::ForeignKeys, 0),
        Some(Navigation {
            schema: "Other.Schema",
            table: "parent",
            identity: TableIdentity {
                database_oid: 11,
                relation_oid: 55
            }
        })
    );
    assert_eq!(
        c.navigation(Section::ReferencedBy, 0)
            .unwrap()
            .identity
            .relation_oid,
        66
    );
}
