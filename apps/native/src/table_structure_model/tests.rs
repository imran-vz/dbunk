#[test]
fn actual_capacity_detail_overlap_and_atomic_refusal_are_charged_and_released() {
    let budget = Rc::new(Cell::new(0));
    let old = Capture::new(snapshot(), budget.clone()).unwrap();
    let old_bytes = old.retained_bytes();
    assert_eq!(budget.get(), old_bytes);
    let mut large = snapshot();
    large.columns[0].default_expression = Some("9".repeat(128 * 1024));
    let replacement = Capture::new(large, budget.clone()).unwrap();
    assert!(replacement.retained_bytes() > old_bytes + DETAIL_BYTE_ALLOWANCE * 128 * 1024);
    assert_eq!(budget.get(), old_bytes + replacement.retained_bytes());
    drop(replacement);
    assert_eq!(budget.get(), old_bytes);
    let held_elsewhere = SHARED_BYTES - old_bytes - 1;
    budget.set(budget.get() + held_elsewhere);
    assert!(Capture::new(snapshot(), budget.clone()).is_err());
    assert_eq!(old.count(Section::Columns), 2);
    assert_eq!(budget.get(), SHARED_BYTES - 1);
    budget.set(budget.get() - held_elsewhere);
    drop(old);
    assert_eq!(budget.get(), 0);
}
