#[test]
fn newline_heavy_detail_refuses_before_formatting_and_preserves_previous_capture() {
    let budget = Rc::new(Cell::new(0));
    let old = Capture::new(snapshot(), budget.clone()).unwrap();
    let old_bytes = budget.get();
    let mut plain = snapshot();
    plain.columns[0].default_expression = Some("x".repeat(40_000));
    let plain_capture = Capture::new(plain, budget.clone()).unwrap();
    drop(plain_capture);
    assert_eq!(budget.get(), old_bytes);
    let mut lines = snapshot();
    lines.columns[0].default_expression = Some("\n".repeat(40_000));
    assert!(lines.checked_heap_bytes().is_some());
    assert!(Capture::new(lines, budget.clone()).is_err());
    assert_eq!(budget.get(), old_bytes);
    assert_eq!(old.count(Section::Columns), 2);
    assert!(old.details(Section::Columns, 0).unwrap().is_some());
    drop(old);
    assert_eq!(budget.get(), 0);
}
#[test]
fn selected_detail_rechecks_bytes_and_logical_runs_independently() {
    let mut data = snapshot();
    data.columns[0].default_expression = Some("x".repeat(4096));
    let mut c = capture(data);
    let bytes = c.largest_detail.bytes;
    c.data.columns[0].default_expression = Some("\n".repeat(4096));
    let mut measured = Counter::default();
    render(&c.data, Section::Columns, 0, &mut measured).unwrap();
    assert_eq!(measured.bytes, bytes);
    assert!(measured.line_breaks > c.largest_detail.line_breaks);
    assert!(c.details(Section::Columns, 0).is_err());
    c.data.columns[0].default_expression = Some("x".repeat(4097));
    assert!(c.details(Section::Columns, 0).is_err());
}
