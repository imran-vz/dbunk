fn existing(origin: Origin) -> Option<BaselineId> {
    origin.existing()
}

/// Engine-neutral operations in plan order (Plan 033 "Operation ordering"):
/// drops, renames, column alterations, adds, column drops, constraint and
/// index adds, foreign keys last, then comments and options.
///
/// A key, check or index whose definition changed is dropped (phase 1) and
/// re-added (phase 6). A foreign key whose local columns change type is
/// re-created around the type change, since engines refuse or silently
/// coerce a mismatched reference; indexes and keys are rebuilt by the
/// engines themselves and are not re-created for a type change.
pub fn plan_steps(baseline: &SchemaBaseline, draft: &SchemaDraft) -> Vec<PlanStep> {
    let old = &baseline.table;
    let new = &draft.table;
    let mut steps = Vec::new();

    let retyped: HashSet<Origin> = new
        .columns
        .iter()
        .filter(|column| {
            old.column(column.origin).is_some_and(|previous| {
                !types_equal(&previous.data_type, &column.data_type)
                    || previous.collation != column.collation
            })
        })
        .map(|column| column.origin)
        .collect();

    // Keys.
    fn key_pairs<'a>(old_keys: Vec<&'a KeyModel>, new_keys: Vec<&'a KeyModel>) -> KeyMatch<'a> {
        match_objects(old_keys.into_iter(), new_keys.into_iter(), |key| key.origin)
    }
    let (pk_pairs, pk_added, pk_removed) = key_pairs(
        old.primary_key.iter().collect(),
        new.primary_key.iter().collect(),
    );
    for key in pk_removed {
        if let Some(id) = existing(key.origin) {
            steps.push(PlanStep::DropPrimaryKey { id });
        }
    }
    for (previous, key) in &pk_pairs {
        let id = existing(key.origin).expect("paired keys are existing");
        if previous.columns != key.columns {
            steps.push(PlanStep::DropPrimaryKey { id });
            steps.push(PlanStep::AddPrimaryKey { origin: key.origin });
        } else if previous.name != key.name && key.name.is_some() {
            steps.push(PlanStep::RenameConstraint {
                object: SchemaObject::PrimaryKey,
                id,
            });
        }
    }
    for key in pk_added {
        steps.push(PlanStep::AddPrimaryKey { origin: key.origin });
    }

    let (unique_pairs, unique_added, unique_removed) =
        key_pairs(old.uniques.iter().collect(), new.uniques.iter().collect());
    for key in unique_removed {
        if let Some(id) = existing(key.origin) {
            steps.push(PlanStep::DropUnique { id });
        }
    }
    for (previous, key) in &unique_pairs {
        let id = existing(key.origin).expect("paired keys are existing");
        if previous.columns != key.columns {
            steps.push(PlanStep::DropUnique { id });
            steps.push(PlanStep::AddUnique { origin: key.origin });
        } else if previous.name != key.name && key.name.is_some() {
            steps.push(PlanStep::RenameConstraint {
                object: SchemaObject::Unique,
                id,
            });
        }
    }
    for key in unique_added {
        steps.push(PlanStep::AddUnique { origin: key.origin });
    }

    // Foreign keys.
    let (fk_pairs, fk_added, fk_removed) =
        match_objects(old.foreign_keys.iter(), new.foreign_keys.iter(), |key| {
            key.origin
        });
    for key in fk_removed {
        if let Some(id) = existing(key.origin) {
            steps.push(PlanStep::DropForeignKey { id });
        }
    }
    for (previous, key) in &fk_pairs {
        let id = existing(key.origin).expect("paired keys are existing");
        let definition_changed = previous.columns != key.columns
            || previous.referenced_schema != key.referenced_schema
            || previous.referenced_table != key.referenced_table
            || previous.referenced_columns != key.referenced_columns
            || previous.on_update != key.on_update
            || previous.on_delete != key.on_delete
            || previous.deferrable != key.deferrable;
        let depends = key.columns.iter().any(|origin| retyped.contains(origin));
        if definition_changed || depends {
            steps.push(PlanStep::DropForeignKey { id });
            steps.push(PlanStep::AddForeignKey { origin: key.origin });
        } else if previous.name != key.name && key.name.is_some() {
            steps.push(PlanStep::RenameConstraint {
                object: SchemaObject::ForeignKey,
                id,
            });
        }
    }
    for key in fk_added {
        steps.push(PlanStep::AddForeignKey { origin: key.origin });
    }

    // Checks.
    let (check_pairs, check_added, check_removed) =
        match_objects(old.checks.iter(), new.checks.iter(), |check| check.origin);
    for check in check_removed {
        if let Some(id) = existing(check.origin) {
            steps.push(PlanStep::DropCheck { id });
        }
    }
    for (previous, check) in &check_pairs {
        let id = existing(check.origin).expect("paired checks are existing");
        if previous.expression != check.expression || previous.enforced != check.enforced {
            steps.push(PlanStep::DropCheck { id });
            steps.push(PlanStep::AddCheck {
                origin: check.origin,
            });
        } else if previous.name != check.name && check.name.is_some() {
            steps.push(PlanStep::RenameConstraint {
                object: SchemaObject::Check,
                id,
            });
        }
    }
    for check in check_added {
        steps.push(PlanStep::AddCheck {
            origin: check.origin,
        });
    }

    // Indexes.
    let (index_pairs, index_added, index_removed) =
        match_objects(old.indexes.iter(), new.indexes.iter(), |index| index.origin);
    for index in index_removed {
        if let Some(id) = existing(index.origin) {
            steps.push(PlanStep::DropIndex { id });
        }
    }
    for (previous, index) in &index_pairs {
        let id = existing(index.origin).expect("paired indexes are existing");
        if previous.unique != index.unique
            || previous.method != index.method
            || previous.members != index.members
            || previous.include != index.include
            || previous.predicate != index.predicate
        {
            steps.push(PlanStep::DropIndex { id });
            steps.push(PlanStep::CreateIndex {
                origin: index.origin,
            });
        } else if previous.name != index.name {
            steps.push(PlanStep::RenameConstraint {
                object: SchemaObject::Index,
                id,
            });
        }
    }
    for index in index_added {
        steps.push(PlanStep::CreateIndex {
            origin: index.origin,
        });
    }

    // Columns.
    for column in &new.columns {
        match old
            .column(column.origin)
            .filter(|_| !column.origin.is_new())
        {
            Some(previous) => {
                let id = existing(column.origin).expect("existing column");
                if previous.name != column.name {
                    steps.push(PlanStep::RenameColumn { id });
                }
                let fields = column_field_changes(previous, column);
                if !fields.is_empty() {
                    steps.push(PlanStep::AlterColumn { id, fields });
                }
                if previous.comment != column.comment {
                    steps.push(PlanStep::SetColumnComment {
                        origin: column.origin,
                    });
                }
            }
            None => {
                steps.push(PlanStep::AddColumn {
                    origin: column.origin,
                });
                if column.comment.is_some() {
                    steps.push(PlanStep::SetColumnComment {
                        origin: column.origin,
                    });
                }
            }
        }
    }
    for column in &old.columns {
        if new.column(column.origin).is_none() {
            if let Some(id) = existing(column.origin) {
                steps.push(PlanStep::DropColumn { id });
            }
        }
    }
    if columns_reordered(old, new) {
        steps.push(PlanStep::ReorderColumns);
    }

    // Table.
    if old.name != new.name {
        steps.push(PlanStep::RenameTable);
    }
    if old.comment != new.comment {
        steps.push(PlanStep::SetTableComment);
    }
    let option_fields: Vec<Field> = option_changes(&old.options, &new.options)
        .into_iter()
        .map(|(field, _, _)| field)
        .collect();
    if !option_fields.is_empty() {
        steps.push(PlanStep::SetTableOptions {
            fields: option_fields,
        });
    }

    // Stable: within a phase, steps keep the order above.
    steps.sort_by_key(PlanStep::phase);
    steps
}

/// True when existing columns changed relative order, or a new column sits
/// before an existing one (so appending would not produce the draft order).
pub fn columns_reordered(old: &TableModel, new: &TableModel) -> bool {
    if !moved_columns(old, new).is_empty() {
        return true;
    }
    let mut seen_new = false;
    for column in &new.columns {
        if column.origin.is_new() {
            seen_new = true;
        } else if seen_new {
            return true;
        }
    }
    false
}

